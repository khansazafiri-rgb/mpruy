/* Pembantu penulisan jawaban khusus kasus (dipakai di cases.js).
   p   = jawaban pasien (say, catatan, ekspresi)
   x   = temuan pemeriksaan fisik oleh dokter (teks, catatan)
   c   = kartu hasil dari suster atau lab (judul, sub, baris "nama=nilai;nama=nilai", ucapan, catatan)
   vit = kartu tanda vital */
function p(say,note,e){return {say:say,note:note,e:e}}
function x(t,note){return {t:t,note:note}}
function c(title,sub,rows,say,note){return {title:title,sub:sub,rows:rows,say:say,note:note}}
function vit(td,n,rr,t,s,extra){
  var rows="Tekanan darah="+td+" mmHg;Nadi="+n+" x/menit;Napas="+rr+" x/menit;Suhu="+t+" °C;SpO₂="+s+(extra?";"+extra[0]+"="+extra[1]:"");
  return c("Tanda vital","Suster Ani",rows,"Ini hasil tanda vitalnya, Dok.",
    "TD "+td+", N "+n+", RR "+rr+", T "+t+", SpO₂ "+s.split(" ")[0]+(extra?", "+extra[0]+" "+extra[1]:""));
}

